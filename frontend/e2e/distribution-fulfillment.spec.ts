    const script = await (await request.post(`${API}/v1/projects/${project.id}/script/generate`, { headers })).json();
    await request.put(`${API}/v1/projects/${project.id}/script`, { headers, data: { segments: [{ kind: "intro", text: "Acme launches a logistics service." }], ticker_lines: script.ticker_lines, lower_thirds: script.lower_thirds, interview_questions: script.interview_questions } });
    await request.post(`${API}/v1/projects/${project.id}/script/approve`, { headers });
    await expect.poll(async () => (await (await request.get(`${API}/v1/projects/${project.id}`, { headers })).json()).state).toBe("final_ready");
    const before = Number((await (await request.get(`${API}/v1/me`, { headers })).json()).credit_balance);
    await page.addInitScript(t => localStorage.setItem("newsagent.token", t), signup.token);
    await page.goto(`/distribution/request?project=${project.id}`);
