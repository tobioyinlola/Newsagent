import { expect, test } from "@playwright/test";

const API = "http://localhost:8000";
const OPS = { Authorization: "Bearer dev:ops@example.com" };

test("shared referral link to verified business signup awards one usable wallet credit", async ({ page, browser, request }) => {
  await page.addInitScript(() => localStorage.setItem("newsagent.token", "dev:ops@example.com"));
  await page.goto("/referrals");
  await expect(page.getByRole("heading", { name: "Invite a business. Earn a credit." })).toBeVisible();
  const link = page.getByLabel("Share this link with another business");
  await expect(link).toHaveValue(/\/signup\?ref=[A-Za-z0-9_-]{24}$/);
  const url = await link.inputValue();
  const before = (await (await request.get(`${API}/v1/referrals`, { headers: OPS })).json()).completed_referrals;
  const initialBalance = Number((await (await request.get(`${API}/v1/me`, { headers: OPS })).json()).credit_balance);
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.getByRole("button", { name: "Copy link" }).click();
  await expect(page.getByRole("status")).toContainText("Referral link copied.");
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(url);
  const guest = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const friend = await guest.newPage(); const email = `referred${Date.now()}@business.example.com`;
  await friend.goto(url);
  await expect(friend.getByText(/You're joining through a referral link/)).toBeVisible();
  await friend.getByLabel("Business name").fill("Referral Browser Business");
  await friend.getByLabel("Country", { exact: true }).fill("Nigeri");
  await friend.getByRole("option", { name: "Nigeria", exact: true }).click();
  await friend.getByLabel("City", { exact: true }).fill("Lago");
  await friend.getByRole("option", { name: "Lagos", exact: true }).first().click();
  await friend.getByLabel("Industry", { exact: true }).selectOption("technology");
  await friend.getByLabel("Work email").fill(email);
  await friend.getByLabel("Password", { exact: true }).fill("correct horse battery");
  await friend.getByLabel("Confirm password", { exact: true }).fill("correct horse battery");
  await friend.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(friend.getByLabel("6-digit code")).toBeVisible();
  expect(Number((await (await request.get(`${API}/v1/me`, { headers: OPS })).json()).credit_balance)).toBe(initialBalance);
  const mail = await (await request.get(`${API}/v1/dev/last-email`, { params: { to: email } })).json();
  const code = /\b(\d{6})\b/.exec(mail.text)![1];
  await friend.getByLabel("6-digit code").fill(code);
  await friend.getByRole("button", { name: "Verify and create workspace" }).click();
  await expect(friend.getByRole("heading", { name: "Welcome, Referral Browser Business" })).toBeVisible({ timeout: 15000 });
  expect(Number((await (await request.get(`${API}/v1/me`, { headers: OPS })).json()).credit_balance)).toBe(initialBalance + 1);
  const repeated = await request.post(`${API}/v1/auth/signup/verify`, { data: { email, code } });
  expect([401, 409]).toContain(repeated.status());
  expect(Number((await (await request.get(`${API}/v1/me`, { headers: OPS })).json()).credit_balance)).toBe(initialBalance + 1);
  await page.reload();
  await expect(page.getByText("Referral Browser Business", { exact: true })).toBeVisible();
  expect((await (await request.get(`${API}/v1/referrals`, { headers: OPS })).json()).completed_referrals).toBe(before + 1);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "/tmp/referrals-mobile.png", fullPage: true });
  await friend.goto("/referrals");
  await expect(friend.getByLabel("Share this link with another business")).not.toHaveValue(url);
  await expect(friend.getByRole("heading", { name: "Businesses referred" }).locator("../..")).toContainText("0");
  await guest.close();
});
