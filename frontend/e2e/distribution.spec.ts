import { expect, test } from "@playwright/test";

const API = "http://localhost:8000";
const OPS = { Authorization: "Bearer dev:ops@example.com" };

test("completed video to distribution draft, checked images, wallet submission, email and back office", async ({ page, request, browser }) => {
  for (const vendor of ["mock", "renderer"]) {
    expect((await request.put(`${API}/v1/admin/vendor-budgets`, { headers: OPS, data: { vendor, limit: "1000" } })).ok()).toBeTruthy();
  }
  const email = `distribution${Date.now()}@example.com`;
  const invited = await (await request.post(`${API}/v1/admin/invites`, { headers: OPS, data: { email, workspace_name: "Distribution Test", credits: "25", spend_cap: "100" } })).json();
  await request.post(`${API}/v1/auth/signup/start`, { data: { invite_code: invited.code, password: "correct horse battery" } });
  const mail = await (await request.get(`${API}/v1/dev/last-email`, { params: { to: email } })).json();
  const signup = await (await request.post(`${API}/v1/auth/signup/verify`, { data: { invite_code: invited.code, code: /\b(\d{6})\b/.exec(mail.text)![1] } })).json();
  const headers = { Authorization: `Bearer ${signup.token}` };
  const project = await (await request.post(`${API}/v1/projects`, { headers, data: { brief_text: "Acme helps farmers sell fresh produce to local businesses in Lagos." } })).json();
  const script = await (await request.post(`${API}/v1/projects/${project.id}/script/generate`, { headers })).json();
  expect((await request.put(`${API}/v1/projects/${project.id}/script`, { headers, data: { segments: [{ kind: "intro", text: "Acme helps farmers sell produce." }], ticker_lines: script.ticker_lines, lower_thirds: script.lower_thirds, interview_questions: script.interview_questions } })).ok()).toBeTruthy();
  expect((await request.post(`${API}/v1/projects/${project.id}/script/approve`, { headers })).ok()).toBeTruthy();
  await expect.poll(async () => (await (await request.get(`${API}/v1/projects/${project.id}`, { headers })).json()).state).toBe("final_ready");
  await page.addInitScript(t => localStorage.setItem("newsagent.token", t), signup.token);
  await page.goto(`/ai-newsroom/${project.id}`);
  await expect(page.getByRole("heading", { name: "Distribute to over 20,000 media outlets" })).toBeVisible();
  await page.getByRole("link", { name: "Choose distribution outlets" }).click();
  await page.getByRole("button", { name: "Start a distribution request" }).click();
  await page.getByLabel("Empire Magazine Africa").check();
  await page.getByLabel("Techpoint Africa").check();
  await expect(page.getByLabel("Selected outlets")).toContainText("2 selected");
  await page.getByRole("button", { name: "View selection" }).click();
  const selection = page.getByRole("dialog", { name: "Your selected outlets" });
  await expect(selection).toContainText("Empire Magazine Africa");
  await expect(selection).toContainText("Total 0 credits");
  await page.getByRole("button", { name: "Close selection" }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  const outletList = page.getByRole("region", { name: "Available media outlets" });
  await expect(outletList).toBeVisible();
  expect(await outletList.evaluate(e => e.scrollHeight > e.clientHeight)).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("searchbox", { name: "Search media outlets" }).fill("Premium Times");
  await expect(page.getByRole("checkbox")).toHaveCount(1);
  await expect(page.getByLabel("Selected outlets", { exact: true })).toContainText("2 selected");
  await page.getByRole("searchbox", { name: "Search media outlets" }).fill("no matching publication");
  await expect(page.getByRole("heading", { name: "No matching outlets" })).toBeVisible();
  await page.getByRole("button", { name: "Show all outlets" }).click();
  await expect(page.getByRole("checkbox")).toHaveCount(47);
  await page.getByRole("button", { name: "Selected only (2)" }).click();
  await expect(page.getByRole("checkbox")).toHaveCount(2);
  await page.getByRole("button", { name: "Selected only (2)" }).click();
  await outletList.evaluate(e => { e.scrollTop = e.scrollHeight; });
  await expect(page.getByRole("checkbox", { name: "P mp Kulture" })).toBeInViewport();
  await outletList.evaluate(e => { e.scrollTop = 0; });
  await page.getByRole("button", { name: "View selection" }).click();
  await expect(page.getByRole("dialog", { name: "Your selected outlets" })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog", { name: "Your selected outlets" })).toHaveCount(0);
  await page.screenshot({ path: "/tmp/distribution-outlets-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect(page.getByRole("complementary", { name: "Selection overview" })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await expect.poll(async () => (await page.locator("#sidebar").boundingBox())?.x).toBe(0);
  await page.screenshot({ path: "/tmp/distribution-outlets-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByLabel("Completed video")).toHaveValue(project.id);
  await page.getByLabel("Headline", { exact: true }).fill("Custom distribution announcement");
  await page.getByLabel("Press announcement", { exact: true }).fill("Our own press announcement with all the details.");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByText("Draft saved", { exact: true })).toBeVisible();
  const draftUrl = page.url();
  const id = new URL(draftUrl).searchParams.get("draft")!;
  const admin = await browser.newContext();
  const ap = await admin.newPage();
  await ap.addInitScript(() => sessionStorage.setItem("newsagent.admin.token", "dev:ops@example.com"));
  await ap.goto("/admin/distribution");
  await expect(ap.getByText(/Custom distribution announcement/)).toBeVisible();
  await expect(ap.getByText(/Unpaid.*Step: contact/)).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Primary contact and company images" })).toBeVisible();
  await page.getByLabel("Contact name", { exact: true }).fill("Ada Obi");
  await page.getByLabel("Contact email", { exact: true }).fill(email);
  await page.getByLabel("Primary phone number", { exact: true }).fill("+2348012345678");
  await page.getByLabel("WhatsApp number", { exact: true }).fill("+2348012345678");
  const png = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.alloc(64)]);
  await page.getByLabel(/Company logo \(required/).setInputFiles({ name: "logo.png", mimeType: "image/png", buffer: png });
  await expect(page.getByText("Company logo uploaded ✓")).toBeVisible();
  await page.getByLabel(/Additional pictures \(optional/).setInputFiles({ name: "picture.png", mimeType: "image/png", buffer: png });
  await expect(page.getByText("Picture 1 uploaded")).toBeVisible();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Review your distribution request" })).toBeVisible();
  await expect(page.getByText("Our own press announcement with all the details.")).toBeVisible();
  await page.getByRole("button", { name: "Pay and submit" }).click();
  await expect(page.getByRole("dialog", { name: "Distribution submitted" })).toContainText("24 hours");
  await page.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByText("Confirmation email sent.")).toBeVisible();
  const confirmation = await (await request.get(`${API}/v1/dev/last-email`, { params: { to: email } })).json();
  expect(confirmation.text).toContain("24 hours");
  await ap.reload();
  const row = ap.locator("details").filter({ hasText: "Custom distribution announcement" });
  await row.locator("summary").click();
  await expect(row).toContainText("Paid 0.0000 credits");
  await expect(row).toContainText("Our own press announcement with all the details.");
  await row.getByLabel("Distribution status", { exact: true }).selectOption("in_progress");
  await expect.poll(async () => (await (await request.get(`${API}/v1/distribution/${id}`, { headers })).json()).status).toBe("in_progress");
  await row.getByRole("button", { name: "Load video, logo and pictures" }).click();
  await expect(row.getByRole("link", { name: "Company logo" })).toBeVisible();
  await expect(row.getByRole("link", { name: "Download selected video" })).toBeVisible();
  await admin.close();
});
