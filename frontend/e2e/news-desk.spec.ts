import { expect, test } from "@playwright/test";
const API = "http://localhost:8000";

test("News Desk source, AI rewrite, verified images, storyboard, public publication and takedown", async ({ page, request }) => {
  await page.addInitScript(() => sessionStorage.setItem("newsagent.admin.token", "dev:ops@example.com"));
  await page.goto("/admin/news-desk");
  await expect(page.getByRole("heading", { name: "News Desk", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "New story", exact: true }).click();
  await page.getByLabel("Source publisher", { exact: true }).fill("Example Technology");
  await page.getByLabel("Original article URL", { exact: true }).fill("https://example.com/technology");
  await page.getByLabel("Source article text", { exact: true }).fill("A technology company has announced a new service for small businesses in Lagos. The service helps teams manage customer appointments and will be available next month. The company says it plans to add more cities later.");
  await page.getByRole("button", { name: "Rewrite with AI", exact: true }).click();
  await expect(page.getByLabel("Headline", { exact: true })).toHaveValue("Technology update: a new chapter for business");
  await expect(page.getByLabel("Presenter script", { exact: true })).not.toBeEmpty();
  await expect(page.getByRole("button", { name: "Generate presenter video — on hold", exact: true })).toBeDisabled();
  await page.getByLabel("Upload story image (PNG/JPEG, up to 5 MB)", { exact: true }).setInputFiles("public/news-segment.jpg");
  await expect(page.getByLabel("Image 1 caption", { exact: true })).toBeVisible();
  await page.getByLabel("Image 1 caption", { exact: true }).fill("The technology launch");
  await page.getByLabel("Image 1 credit", { exact: true }).fill("Example photographer");
  await page.getByLabel("Scene 1 image", { exact: true }).selectOption({ index: 1 });
  await page.getByLabel("Scene 1 motion", { exact: true }).selectOption("pan_left");
  await expect(page.getByRole("region", { name: "Image sequence preview", exact: true }).locator("img")).toHaveAttribute("data-motion", "pan_left");
  await page.getByRole("button", { name: "Play image preview", exact: true }).click();
  await expect(page.getByRole("button", { name: "Pause preview", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Pause preview", exact: true }).click();
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("status", { name: "News Desk update", exact: true })).toHaveText("Draft saved.");
  await page.getByRole("checkbox", { name: /I reviewed the facts/ }).check();
  await page.getByRole("button", { name: "Publish story", exact: true }).click();
  await expect(page.getByRole("status", { name: "News Desk update", exact: true })).toContainText("Story published");
  const link = page.getByRole("link", { name: "View published story", exact: true });
  const path = await link.getAttribute("href");
  await page.screenshot({ path: "/tmp/cf-news-desk-admin.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 720 });
  const cards = await (await request.get(`${API}/v1/public/stories`)).json();
  expect(cards[0].category).toBe("CF Technology Breaking News");
  await page.goto("/latest-stories");
  await expect(page.getByRole("heading", { name: "CF Technology Breaking News", exact: true })).toBeVisible();
  await page.goto(path!);
  await expect(page.getByText("Source reporting:", { exact: false })).toBeVisible();
  await expect(page.getByRole("link", { name: "Example Technology", exact: true })).toHaveAttribute("href", "https://example.com/technology");
  await expect(page.locator("video")).toHaveCount(0);
  await expect(page.getByText("The technology launch · Example photographer", { exact: true })).toBeVisible();
  await page.screenshot({ path: "/tmp/cf-technology-news-public.png", fullPage: true });
  await page.goto("/admin/news-desk");
  await page.getByRole("button", { name: /Technology update: a new chapter/ }).click();
  await page.getByRole("button", { name: "Unpublish story", exact: true }).click();
  await expect(page.getByRole("status", { name: "News Desk update", exact: true })).toContainText("removed from public");
  expect((await request.get(`${API}/v1/public/stories/${cards[0].slug}`)).status()).toBe(404);
});
